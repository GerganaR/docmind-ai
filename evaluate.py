"""Run the evaluation question set against the real pipeline and write a results report.

Usage (requires OPENAI_API_KEY and a prior `python ingest.py`):
    python evaluate.py
    python evaluate.py --output docs/evaluation-results.md

Metrics (deliberately simple and transparent):
- retrieval hit: the expected source file is among the chunks passed to the LLM
- answer match: every expected keyword appears in the answer (case-insensitive)
- refusal correct: unanswerable questions return the insufficient-context response
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

import openai

from docmind.config import ConfigError, load_settings
from docmind.factory import make_pipeline
from docmind.pipeline import EmptyIndexError


@dataclass(frozen=True)
class EvalCase:
    id: str
    question: str
    answerable: bool
    expected_source: str | None = None
    expected_keywords: tuple[str, ...] = field(default_factory=tuple)


# Keep in sync with docs/evaluation.md
CASES: list[EvalCase] = [
    EvalCase("Q1", "How many vacation days do full-time employees get, and can unused days be carried over?",
             True, "employee_handbook.md", ("28", "5")),
    EvalCase("Q2", "How quickly must a phishing email be reported, and to whom?",
             True, "it_security_policy.md", ("one hour", "security@acme-analytics.example")),
    EvalCase("Q3", "How much does the Professional plan cost?",
             True, "product_faq.txt", ("79",)),
    EvalCase("Q4", "Where is customer data stored?",
             True, "product_faq.txt", ("Frankfurt",)),
    EvalCase("Q5", "How many days per week can employees work remotely?",
             True, "employee_handbook.md", ("three",)),
    EvalCase("Q6", "What is the minimum password length?",
             True, "it_security_policy.md", ("14",)),
    EvalCase("Q7", "What happens to workspace data after a subscription is cancelled?",
             True, "product_faq.txt", ("30 days",)),
    EvalCase("Q8", "Is there a native Salesforce connector?",
             True, "product_faq.txt", ("not yet",)),
    EvalCase("N1", "What is the name of the CEO of Acme Analytics?", False),
    EvalCase("N2", "What is the current stock price of Acme Analytics?", False),
    EvalCase("N3", "What will the weather be like in Berlin tomorrow?", False),
    EvalCase("N4", "How many vacation days do interns get?", False),
]


def run(output: Path) -> int:
    pipeline = make_pipeline(load_settings())
    rows = []
    for case in CASES:
        answer = pipeline.answer(case.question)
        passed_sources = {r.chunk.source for r in answer.retrieved if r.distance <= pipeline.max_distance}
        best = min(answer.retrieved, key=lambda r: r.distance) if answer.retrieved else None

        if case.answerable:
            hit = case.expected_source in passed_sources
            match = answer.sufficient_context and all(
                k.lower() in answer.text.lower() for k in case.expected_keywords)
            verdict = "PASS" if (hit and match) else "FAIL"
        else:
            hit = None
            match = not answer.sufficient_context
            verdict = "PASS" if match else "FAIL"

        rows.append((case, answer, hit, match, verdict, best))
        print(f"{case.id}: {verdict}")

    answerable = [r for r in rows if r[0].answerable]
    unanswerable = [r for r in rows if not r[0].answerable]
    settings = load_settings()

    lines = [
        "# Evaluation Results (generated)",
        "",
        f"Generated by `python evaluate.py` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC}.",
        f"Models: embeddings `{settings.embedding_model}`, chat `{settings.chat_model}`. "
        f"top_k={pipeline.top_k}, max_distance={pipeline.max_distance}, "
        f"chunk_size={settings.chunk_size}, overlap={settings.chunk_overlap}.",
        "",
        "## Summary",
        "",
        f"- Retrieval hit rate (answerable): {sum(bool(r[2]) for r in answerable)}/{len(answerable)}",
        f"- Answer keyword match (answerable): {sum(bool(r[3]) for r in answerable)}/{len(answerable)}",
        f"- Correct refusals (unanswerable): {sum(bool(r[3]) for r in unanswerable)}/{len(unanswerable)}",
        f"- Overall pass: {sum(r[4] == 'PASS' for r in rows)}/{len(rows)}",
        "",
        "## Per-question results",
        "",
    ]
    for case, answer, hit, match, verdict, best in rows:
        cited = ", ".join(f"{c.chunk.source}#{c.chunk.chunk_index}" for c in answer.citations) or "-"
        best_txt = (f"{best.chunk.source}#{best.chunk.chunk_index} (similarity {best.similarity:.2f})"
                    if best else "-")
        lines += [
            f"### {case.id} - {verdict}",
            "",
            f"**Question:** {case.question}",
            "",
            f"**Answer:** {answer.text}",
            "",
            f"- Expected: {'answer from ' + str(case.expected_source) if case.answerable else 'insufficient-context response'}",
            f"- Retrieval hit: {'n/a' if hit is None else hit} | Answer/refusal correct: {match}",
            f"- Cited: {cited}",
            f"- Top retrieved chunk: {best_txt}",
            "",
        ]

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nWrote {output}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Evaluate DocMind AI on a fixed question set.")
    parser.add_argument("--output", type=Path, default=Path("docs/evaluation-results.md"))
    args = parser.parse_args(argv)
    try:
        return run(args.output)
    except (ConfigError, EmptyIndexError) as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1
    except openai.OpenAIError as exc:
        print(f"OpenAI API error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
